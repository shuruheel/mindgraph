// Regenerate mcp_contract.json from a mindgraph-mcp checkout, so the Hermes
// tool schemas and memory instructions cannot drift from the MCP server's
// general profile.
//
//   node scripts/sync_from_mcp.mjs [path/to/mindgraph-mcp]
//
// Uses the MCP checkout's own esbuild; nothing is installed here.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdtempSync, existsSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const mcp = path.resolve(process.argv[2] ?? path.join(here, "..", "..", "mindgraph-mcp"));
const require = createRequire(path.join(mcp, "package.json"));
const esbuild = require("esbuild");
const version = JSON.parse(readFileSync(path.join(mcp, "package.json"), "utf8")).version;
const hasInstructionBuilder = existsSync(path.join(mcp, "src", "instructions.ts"));

const out = path.join(mkdtempSync(path.join(tmpdir(), "mg-contract-")), "tools.mjs");
await esbuild.build({
  stdin: {
    contents: 'export { toolsForProfile } from "./src/tools.ts";' +
      (hasInstructionBuilder ? 'export { buildInstructions } from "./src/instructions.ts";' : ''),
    resolveDir: mcp,
    loader: "ts",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: out,
  define: { __PACKAGE_VERSION__: JSON.stringify(version) },
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  logLevel: "error",
});
const { toolsForProfile, buildInstructions } = await import(pathToFileURL(out).href);

// Hermes supplies invocation context itself (session id, turn); the model never sees it.
// Repository/code fields belong to the coding profile's code adapter, which Hermes lacks.
// `scope: workspace` requires the local MCP code adapter, also absent in Hermes.
const HERMES_OMITTED = ["invocation_context", "code_refs", "repo", "repo_space_uid", "scope"];
const tools = toolsForProfile("general").map((tool) => {
  const parameters = structuredClone(tool.inputSchema);
  let description = tool.description;
  if (tool.name === "mindgraph_memory" && parameters.properties?.handle) {
    // open/index resolve local repository-memory handles through the MCP code
    // adapter, which Hermes does not have. Do not advertise unusable actions.
    parameters.properties.action.enum = parameters.properties.action.enum.filter(
      (action) => action !== "open" && action !== "index",
    );
    parameters.properties.action.description = "Read integration status or bounded memory context";
    delete parameters.properties.handle;
    const start = description.indexOf("Use action='open'");
    const end = description.indexOf("This tool never writes", start);
    if (start < 0 || end < 0) throw new Error("local memory handle instructions changed; review Hermes adaptation");
    description = description.slice(0, start) + description.slice(end);
  }
  for (const key of HERMES_OMITTED) delete parameters.properties?.[key];
  // Hermes returns the final tool result; its provider API has no progress channel.
  if (parameters.properties?.wait_seconds) {
    parameters.properties.wait_seconds.description = parameters.properties.wait_seconds.description
      .replace(", reporting progress,", ",");
  }
  if (Array.isArray(parameters.required)) {
    parameters.required = parameters.required.filter((key) => !HERMES_OMITTED.includes(key));
  }
  return { name: tool.name, description, parameters };
});

// Released MCP versions now export a pure instruction builder. Import that
// module, never the server entry point (which starts transports and hooks).
// Keep support for older releases whose instructions were an inline template.
let sourceInstructions;
if (hasInstructionBuilder) {
  sourceInstructions = buildInstructions("general", "generic");
} else {
  const index = readFileSync(path.join(mcp, "src", "index.ts"), "utf8");
  // Consume escapes as pairs so an escaped ` followed by ; cannot end a template.
  const match = index.match(/let INSTRUCTIONS = `((?:\\[\s\S]|[^`\\])*)`;/);
  if (!match) throw new Error("INSTRUCTIONS template not found in src/index.ts");
  sourceInstructions = match[1].replace(/\\`/g, "`");
}
const GENERATED_TOOLS_CLAUSE = ", plus any ontology tools generated by the active schema";
if (!sourceInstructions.includes(GENERATED_TOOLS_CLAUSE)) {
  throw new Error("instructions no longer mention generated ontology tools; review the Hermes rewrite");
}
// Hermes cannot route tools that appear after initialize(), so they are not exposed.
const instructions = sourceInstructions
  .replace(GENERATED_TOOLS_CLAUSE, "")
  .split("\n")
  .filter((line) => !line.includes("mindgraph_code") && !line.includes("`code`") && !line.includes("Typed code anchors"))
  .join("\n");

writeFileSync(
  path.join(here, "..", "mcp_contract.json"),
  JSON.stringify({ mcp_version: version, tools, instructions }, null, 2) + "\n",
);
console.log(`mcp_contract.json: mindgraph-mcp ${version}, ${tools.length} tools`);
