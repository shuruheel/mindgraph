// Regenerate mcp_contract.json from a mindgraph-mcp checkout, so the Hermes
// tool schemas and memory instructions cannot drift from the MCP server's
// general profile.
//
//   node scripts/sync_from_mcp.mjs [path/to/mindgraph-mcp]
//
// Uses the MCP checkout's own esbuild; nothing is installed here.
import { createRequire } from "node:module";
import { readFileSync, writeFileSync, mkdtempSync } from "node:fs";
import { tmpdir } from "node:os";
import path from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const here = path.dirname(fileURLToPath(import.meta.url));
const mcp = path.resolve(process.argv[2] ?? path.join(here, "..", "..", "mindgraph-mcp"));
const require = createRequire(path.join(mcp, "package.json"));
const esbuild = require("esbuild");
const version = JSON.parse(readFileSync(path.join(mcp, "package.json"), "utf8")).version;

const out = path.join(mkdtempSync(path.join(tmpdir(), "mg-contract-")), "tools.mjs");
await esbuild.build({
  stdin: {
    contents: 'export { toolsForProfile } from "./src/tools.ts";',
    resolveDir: mcp,
    loader: "ts",
  },
  bundle: true,
  platform: "node",
  format: "esm",
  outfile: out,
  define: { __PACKAGE_VERSION__: JSON.stringify(version) },
  banner: { js: "import { createRequire as __cr } from 'node:module'; const require = __cr(import.meta.url);" },
  logLevel: "error",
});
const { toolsForProfile } = await import(pathToFileURL(out).href);

// Hermes supplies invocation context itself (session id, turn); the model never sees it.
// Repository/code fields belong to the coding profile's code adapter, which Hermes lacks.
const HERMES_OMITTED = ["invocation_context", "code_refs", "repo", "repo_space_uid"];
const tools = toolsForProfile("general").map((tool) => {
  const parameters = structuredClone(tool.inputSchema);
  for (const key of HERMES_OMITTED) delete parameters.properties?.[key];
  if (Array.isArray(parameters.required)) {
    parameters.required = parameters.required.filter((key) => !HERMES_OMITTED.includes(key));
  }
  return { name: tool.name, description: tool.description, parameters };
});

// The instructions are a template literal in index.ts; the general profile drops code lines.
const index = readFileSync(path.join(mcp, "src", "index.ts"), "utf8");
const match = index.match(/let INSTRUCTIONS = `([\s\S]*?)`;/);
if (!match) throw new Error("INSTRUCTIONS template not found in src/index.ts");
const GENERATED_TOOLS_CLAUSE = ", plus any ontology tools generated by the active schema";
if (!match[1].includes(GENERATED_TOOLS_CLAUSE)) {
  throw new Error("instructions no longer mention generated ontology tools; review the Hermes rewrite");
}
// Hermes cannot route tools that appear after initialize(), so they are not exposed.
const instructions = match[1]
  .replace(GENERATED_TOOLS_CLAUSE, "")
  .replace(/\\`/g, "`")
  .split("\n")
  .filter((line) => !line.includes("mindgraph_code") && !line.includes("`code`") && !line.includes("Typed code anchors"))
  .join("\n");

writeFileSync(
  path.join(here, "..", "mcp_contract.json"),
  JSON.stringify({ mcp_version: version, tools, instructions }, null, 2) + "\n",
);
console.log(`mcp_contract.json: mindgraph-mcp ${version}, ${tools.length} tools`);
